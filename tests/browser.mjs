import {chromium} from 'playwright-core'
import {build} from 'esbuild'
import {mkdir,readFile} from 'node:fs/promises'
import assert from 'node:assert/strict'
import {createServer} from 'node:http'
let browser
const fixture=(await build({entryPoints:['tests/fixture.ts'],bundle:true,format:'iife',write:false})).outputFiles[0].text
const css=await readFile('styles.css','utf8')
const server=createServer((_req,res)=>{res.setHeader('Content-Type','text/html');res.end('<!DOCTYPE html><html><meta name="viewport" content="width=device-width, initial-scale=1"><style>html,body,#app{width:100%;height:100%;padding:0;margin:0;overflow:hidden}'+css+'</style><div id="app"></div><script>'+fixture+'</script>')})
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve))
try{
 browser=await chromium.launch({headless:true,executablePath:process.env.BROWSER_BIN??'/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge',args:['--no-first-run']})
 const p=await browser.newPage({viewport:{width:386,height:678},hasTouch:true,reducedMotion:'reduce'})
 p.setDefaultTimeout(6500)
 const errors=[];p.on('pageerror',e=>errors.push(e.message))
 await p.goto('http://127.0.0.1:'+server.address().port)
 const button=(name)=>p.getByRole('button',{name,exact:true})
 const root=p.locator('.fb-root'), body=p.locator('.cm-content'), title=p.getByRole('textbox',{name:'Page title'})
 await mkdir('test-output',{recursive:true})
 await button('Open notebook').waitFor()
 await p.screenshot({path:'test-output/01-cover.png'})
 await button('Open notebook').click()
 await button('New page').click()
 await title.fill('A notebook page')
 await body.fill('A useful meeting reminder.\n\n## Next steps\nCall the team.')
 await p.waitForTimeout(430)
 await p.evaluate(()=>window.fixture.focusPage(9,16))
 await button('Text marks').click()
 await button('Circle').click()
 await p.locator('.fb-mark-circle').waitFor()
 assert.equal(await p.locator('.fb-mark-circle').textContent(),'meeting')
 await button('Close marks').click()
 await p.evaluate(()=>window.fixture.focusPage(12,12))
 await p.keyboard.insertText('ee')
 await p.waitForTimeout(450)
 assert.match(await p.locator('.fb-mark-circle').textContent(),/meeeeting/)
 await p.getByRole('button',{name:'Done',exact:true}).click()
 assert.equal(await root.getAttribute('data-layout'),'narrow')
 assert.ok((await p.locator('.fb-page').boundingBox()).width>=380)
 assert.equal(await p.evaluate(()=>window.fixture.count()),1)
 assert.equal(await p.locator('.fb-read-heading').textContent(),'Next steps')
 await p.screenshot({path:'test-output/02-portrait.png'})
 await button('Bookmark page').click()
 await button('New page').click()
 await title.fill('Second page')
 await body.fill('The page survives a resize.')
 await p.setViewportSize({width:871,height:669})
 await p.waitForFunction(()=>document.querySelector('.fb-root')?.dataset.layout==='wide')
 assert.equal(await body.textContent(),'The page survives a resize.')
 assert.equal(await title.inputValue(),'Second page')
 assert.equal(await p.evaluate(()=>window.fixture.count()),2)
 assert.equal(await p.locator('.fb-facing-title').textContent(),'A notebook page')
 await p.getByRole('button',{name:'Done',exact:true}).click()
 await p.screenshot({path:'test-output/03-wide.png'})
 await button('Previous page').click()
 await p.locator('.fb-mark-circle').waitFor()
 await button('Bookmarks').click()
 await p.getByRole('button',{name:/A notebook page/}).last().click()
 assert.equal(await title.inputValue(),'A notebook page')
 await button('Appearance').click()
 await p.getByLabel('Paper',{exact:true}).selectOption('sky')
 assert.equal(await root.getAttribute('data-paper'),'sky')
 await p.getByLabel('Ruling',{exact:true}).selectOption('dotted')
 await button('Save').click()
 await p.evaluate(()=>window.fixture.destroy())
 await p.evaluate(()=>window.fixture.start())
 await button('Open notebook').click()
 await p.locator('.fb-mark-circle').waitFor()
 assert.equal(await root.getAttribute('data-paper'),'sky')
 assert.equal(await root.getAttribute('data-ruling'),'dotted')
 assert.equal(await title.inputValue(),'A notebook page')
 // Same phrase twice: mark only the second, narrow enough that it wraps,
 // change earlier text and verify exactly one mark stays at the second occurrence.
 await button('Type or finish editing').click()
 const phrase='follow the student after a warm handoff'
 const repeated=phrase+' first.\n\nA short lead-in so we '+phrase+' second.'
 await body.fill(repeated)
 await p.waitForTimeout(450)
 const at=repeated.lastIndexOf(phrase)
 await p.evaluate(([a,b])=>window.fixture.focusPage(a,b),[at,at+phrase.length])
 await button('Text marks').click()
 await button('Underline').click()
 await button('Close marks').click()
 await p.setViewportSize({width:386,height:678})
 await p.waitForFunction(()=>document.querySelector('.fb-root')?.dataset.layout==='narrow')
 const painted=p.locator('.fb-mark-underline')
 assert.equal(await painted.count(),1)
 assert.equal(await painted.textContent(),phrase)
 assert.ok(await painted.evaluate(e=>e.getClientRects().length>=2))
 await p.evaluate(()=>window.fixture.focusPage(0,0))
 await p.keyboard.insertText('Start: ')
 await p.waitForTimeout(450)
 assert.ok(await painted.evaluate(e=>e.closest('.cm-line').textContent.endsWith(' second.')))
 await p.getByRole('button',{name:'Done',exact:true}).click()
 await p.evaluate(()=>window.fixture.destroy())
 await p.evaluate(()=>window.fixture.start())
 await button('Open notebook').click()
 await painted.waitFor()
 assert.ok(await painted.evaluate(e=>e.closest('.cm-line').textContent.endsWith(' second.')))
 await button('Type or finish editing').click()
 const shifted=at+7
 await p.evaluate(([a,b])=>window.fixture.focusPage(a,b),[shifted,shifted+phrase.length])
 await p.keyboard.press('Backspace')
 await p.waitForTimeout(450)
 assert.equal(await painted.count(),0)
 await button('Text marks').click()
 await p.getByText(/need review/).waitFor()
 await button('Close marks').click()
 await p.getByRole('button',{name:'Done',exact:true}).click()
 await p.setViewportSize({width:768,height:999})
 await p.waitForFunction(()=>document.querySelector('.fb-root')?.dataset.layout==='narrow')
 await button('Type or finish editing').click()
 await body.fill('Unsaved local draft should remain.')
 await p.evaluate(()=>window.fixture.change(1,'Actual synced version.'))
 await p.waitForTimeout(700)
 assert.equal(await body.textContent(),'Unsaved local draft should remain.')
 assert.equal((await p.evaluate(()=>window.fixture.pages()))[0].body,'Actual synced version.')
 await p.evaluate(()=>window.fixture.destroy())
 assert.match((await p.evaluate(()=>window.fixture.recover()))[0],/Unsaved local draft/)
 assert.deepEqual(errors,[])
 console.log('PASS: cover; create/write; mark edit and persistence; 386/871 responsive layouts and portrait aspect; bookmarks; appearance; external conflict and recovery; no browser errors.')
}finally{
 await browser?.close()
 await new Promise(resolve=>server.close(resolve))
}
